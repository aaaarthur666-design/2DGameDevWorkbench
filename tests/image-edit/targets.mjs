  check((await readImageTarget(root, manifest, { kind: 'image-task', taskId: candidate.taskId })).sha256, candidate.sha256);
  const allTargets = await listImageTargets(root, manifest, { limit: 200 });
  check(allTargets.issues, undefined);
  check([...new Set(allTargets.targets.map(target => target.targetRef.kind))].sort((a, b) => a.localeCompare(b)), ['image-task', 'interactable']);
