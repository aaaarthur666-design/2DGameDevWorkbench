import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { createHash } from 'node:crypto';
import sharp from 'sharp';
import JSZip from 'jszip';
import { createDocument, applyDocumentCommands, getDocument } from '../../lib/workbench/editor-documents.mjs';
import { adoptDocumentImage } from '../../lib/workbench/document-assets.mjs';
import { observeScene } from '../../lib/workbench/scene-observation.mjs';
import { exportSceneDocument } from '../../lib/workbench/scene-export.mjs';
import { readMapProjectPackage } from '../../features/map-stitcher/project-package.mjs';
import { readScenePackage } from '../../features/scene-composer/package.mjs';

const root = await mkdtemp(path.join(os.tmpdir(), 'forge-route-a-'));
const manifest = { workspace: { outputDirectory: 'outputs', taskDirectory: 'work/tasks', documentDirectory: 'work/editor-documents', sceneExportDirectory: 'work/scene-exports' } };
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
try {
  async function imageTask(id, kind, png) {
    const width = (await sharp(png).metadata()).width;
    const height = (await sharp(png).metadata()).height;
    const output = `outputs/${id}`;
    await mkdir(path.join(root, output), { recursive: true });
    await mkdir(path.join(root, 'work/tasks'), { recursive: true });
    await writeFile(path.join(root, output, 'image.png'), png);
    await writeFile(path.join(root, output, 'result.json'), JSON.stringify({ image: 'image.png', kind, sha256: hash(png), width, height }));
    await writeFile(path.join(root, 'work/tasks', `${id}.json`), JSON.stringify({ id, capabilityId: 'image-assets', status: 'completed', input: { operation: kind === 'prop' ? 'generate-prop' : 'generate-background', name: id, prompt: 'Test-only image fixture; not model output.' }, outputs: [`${output}/image.png`, `${output}/result.json`] }));
    return { sourceTaskId: id, sha256: hash(png) };
  }
  const bg = await sharp({ create: { width: 128, height: 96, channels: 4, background: '#264653' } }).png().toBuffer();
  const prop = await sharp({ create: { width: 32, height: 32, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } }).composite([{ input: await sharp({ create: { width: 16, height: 16, channels: 4, background: '#e9c46a' } }).png().toBuffer(), left: 8, top: 8 }]).png().toBuffer();
  const background = await imageTask('test-background', 'background', bg);
  const item = await imageTask('test-prop', 'prop', prop);
  const { document: emptyScene } = await createDocument(root, manifest, { kind: 'scene', commandId: 'create-scene', name: '路线 A 测试' });
  const sceneAdoption = { documentId: emptyScene.id, expectedRevision: 1, commandId: 'adopt-background', ...background };
  const { document: mapped } = await adoptDocumentImage(root, manifest, sceneAdoption);
  assert.equal(mapped.revision, 2);
  assert.equal(mapped.content.map.layers[0].width, 128);
  const originalSource = Buffer.from(mapped.content.map.source.split(',')[1], 'base64');
  const mapSource = await readMapProjectPackage(originalSource);
  assert.equal(mapSource.draft.snapshot.tiles[0].images.overall.generation.sha256, background.sha256);
  const retry = await adoptDocumentImage(root, manifest, sceneAdoption);
  assert.equal(retry.replayed, true, 'Background adoption is deterministic and idempotent.');
  assert.equal(retry.document.revision, 2);
  const { document: emptyObject } = await createDocument(root, manifest, { kind: 'interactable', commandId: 'create-object', name: '查看路牌' });
  const definitionId = emptyObject.content.objects[0].definitionId;
  const { document: object } = await adoptDocumentImage(root, manifest, { documentId: emptyObject.id, expectedRevision: 1, commandId: 'adopt-prop', definitionId, ...item });
  assert.equal(object.content.projectId, emptyObject.id);
  assert.equal(object.content.objects[0].definitionId, definitionId);
  assert.equal(object.content.objects[0].behavior.kind, 'inspect');
  assert.equal(object.content.assets[0].generation.sha256, item.sha256);
  const { document: placed } = await applyDocumentCommands(root, manifest, { documentId: mapped.id, expectedRevision: 2, commandId: 'place-sign', commands: [{ type: 'import-material', project: object.content, definitionId, materialId: 'sign-material' }, { type: 'add-instance', materialId: 'sign-material', instanceId: 'sign', x: 40, y: 70 }] });
  const before = await observeScene(root, manifest, placed, { overlay: false });
  const { document: moved } = await applyDocumentCommands(root, manifest, { documentId: mapped.id, expectedRevision: 3, commandId: 'move-sign', commands: [{ type: 'move-instances', ids: ['sign'], x: 80, y: 70 }] });
  const after = await observeScene(root, manifest, moved, { overlay: false });
  assert.notEqual(before.images[0].sha256, after.images[0].sha256);
  assert.equal(after.objects[0].anchor.x, 80);
  assert.equal(after.revision, 4);
  assert.equal(moved.content.map.layers[0].source, mapped.content.map.layers[0].source, 'Moving the prop must preserve the background.');
  await assert.rejects(adoptDocumentImage(root, manifest, { ...sceneAdoption, commandId: 'stale-adoption' }), { code: 'REVISION_CONFLICT', status: 409 });
  const exported = await exportSceneDocument(root, manifest, { documentId: moved.id, revision: moved.revision });
  assert.equal(exported.documentContentHash, moved.contentHash);
  assert.equal(exported.engineValidated, false);
  const sourcePath = exported.outputs.find((name) => name.endsWith('/scene-source.zip'));
  const restored = await readScenePackage(await readFile(path.join(root, sourcePath)));
  assert.equal(restored.instances[0].x, 80);
  assert.equal(restored.materials[0].project.assets[0].generation.sha256, item.sha256);
  const godot = await JSZip.loadAsync(await readFile(path.join(root, exported.outputs.find((name) => name.endsWith('/scene-godot.zip')))));
  const sceneFile = await godot.file(`scenes/${moved.id}/scene.tscn`).async('string');
  assert.match(sceneFile, /instance_id = "sign"/);
  assert.match(sceneFile, /position = Vector2\(80, 38\)/);
  assert.equal((await getDocument(root, manifest, { documentId: moved.id, revision: 2 })).document.content.instances.length, 0);
  await writeFile(path.join(root, 'outputs/test-prop/image.png'), bg);
  await assert.rejects(adoptDocumentImage(root, manifest, { documentId: emptyObject.id, expectedRevision: 2, commandId: 'changed-prop', definitionId, ...item }), /透明|变化/);
  console.log('Route A: immutable background/prop adoption → shared scene → edit → observe → source/Godot export passed. Fixture art only; no provider or engine execution.');
} finally {
  assert.ok(path.dirname(root) === path.resolve(os.tmpdir()) && path.basename(root).startsWith('forge-route-a-'), 'Unsafe test cleanup path');
  await rm(root, { recursive: true, force: true });
}
