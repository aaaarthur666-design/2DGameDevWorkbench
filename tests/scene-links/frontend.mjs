import assert from 'node:assert/strict';
import { createObject, createProject } from '../../features/interactable-editor/contract.mjs';
import { addInstance, addMaterial, createScene } from '../../features/scene-composer/model.mjs';
import { sceneLinkDiagnostics } from '../../features/scene-composer/links.mjs';
import { canCopySourceToggle, linkDescription, linkDiagnosticLabel, linkSourceEvents, linkTargetActions, reconcileLinkDraft } from '../../features/scene-composer/link-editor.mjs';
import { previewBehaviorLabel, previewEventLabel } from '../../features/scene-composer/preview-feedback.mjs';
import { createSceneSimulation } from '../../features/scene-composer/simulation.mjs';

const scene = createScene('联动编辑验收');
function object(kind, name) {
  const project = createProject(); project.objects = [createObject(kind)];
  const definition = project.objects[0]; definition.displayName = name; definition.content.pages = [];
  definition.activation.mode = 'external_request';
  const material = addMaterial(scene, project, definition.definitionId);
  return addInstance(scene, material.id, 100 + scene.instances.length * 100, 100);
}
const button = object('toggle', '拉杆'), door = object('toggle', '门'), key = object('pickup', '钥匙'), lamp = object('inspect', '灯');
assert(linkSourceEvents(scene, button.id).includes('toggled'));
assert(!linkSourceEvents(scene, key.id).includes('toggled'));
assert(linkSourceEvents(scene, key.id).includes('picked_up'));
assert(!linkSourceEvents(scene, button.id).includes('picked_up'));
assert(linkTargetActions(scene, door.id).includes('set_toggle'));
assert(!linkTargetActions(scene, lamp.id).includes('set_toggle'));
assert.equal(canCopySourceToggle(scene, key.id), false);
const link = { id: 'ui-link', sourceInstanceId: button.id, event: 'toggled', targetInstanceId: door.id, action: 'set_toggle', value: 'source_toggle', enabled: true };
const copied = reconcileLinkDraft(scene, link, { sourceInstanceId: key.id, targetInstanceId: lamp.id });
assert.equal(copied.event, 'interaction_finished');
assert.equal(copied.action, 'set_enabled');
assert.equal(copied.value, true, 'changing a source/target removes stale incompatible form values');
assert.equal(link.value, 'source_toggle', 'form reconciliation leaves the saved link untouched');
assert.match(linkDescription(scene, link), /拉杆.*门.*跟随来源开关/);
scene.links = [link];
const broken = { ...scene, instances: scene.instances.filter(instance => instance.id !== door.id) };
const diagnostic = sceneLinkDiagnostics(broken)[0];
assert.equal(diagnostic.code, 'LINK_ENDPOINT_MISSING');
assert.match(linkDiagnosticLabel(broken, diagnostic), /来源或目标物件已不存在/);
assert(!linkDiagnosticLabel(broken, diagnostic).includes('ui-link'), 'visible warnings identify the objects, not storage IDs');
const sim = createSceneSimulation(scene);
assert.match(previewBehaviorLabel(sim.objects.find(instance => instance.id === door.id)), /状态 A/);
sim.request(sim.objects.find(instance => instance.id === button.id));
const doorState = sim.getLinkState(door.id);
assert.equal(doorState.toggleState, true);
assert.equal(doorState.successCount, 0);
assert.match(previewBehaviorLabel(sim.objects.find(instance => instance.id === door.id)), /状态 B/);
const applied = sim.events.find(event => event.name === 'link_applied');
assert.match(previewEventLabel(scene, applied), /拉杆 → 门.*设置开关状态：开启/);
assert.match(previewEventLabel(scene, { ...applied, changed: false }), /状态未变化/);
assert.match(previewEventLabel(scene, { ...applied, name: 'link_skipped', reason: 'target_unavailable' }), /目标不可用/);
assert.match(previewEventLabel(scene, { ...applied, name: 'link_error', reason: 'action_limit' }), /联动已停止/);
assert.equal(scene.instances.length, 4);
assert.equal(scene.materials.find(material => material.id === door.materialId).project.objects[0].behavior.initialToggle, false, 'preview feedback does not write runtime state into authored defaults');
console.log('Scene links frontend: compatible choices, stale form-value repair, readable broken-link diagnostics, and real simulated setter/no-op/error feedback passed.');
